// 阶段八十九 · B6：看板联动/下钻 纯逻辑层测试（无 DOM，直接断言维度翻译与数据过滤）。
import { describe, it, expect } from 'vitest';
import { 取点击维度, 按条件过滤数据, 取下一维度, 应用下钻 } from '../utils/看板联动';

const 配置 = {
  X轴: '区域', Y轴: ['销售额'], 类型: 'bar',
  数据: [
    { 区域: '华东', 销售额: 100, 月份: '1月' },
    { 区域: '华东', 销售额: 120, 月份: '2月' },
    { 区域: '华南', 销售额: 80, 月份: '1月' },
    { 区域: '华南', 销售额: 90, 月份: '2月' },
  ],
};

describe('看板联动 · 取点击维度', () => {
  it('X轴 + params.name → {维度,值}', () => {
    expect(取点击维度(配置, { name: '华南' })).toEqual({ 维度: '区域', 值: '华南' });
  });

  it('无 X 轴：回落数据第一列', () => {
    expect(取点击维度({ 数据: [{ 城市: '上海', 值: 1 }] }, { name: '上海' })).toEqual({ 维度: '城市', 值: '上海' });
  });

  it('空名 / 无 params → null（空白区点击不联动）', () => {
    expect(取点击维度(配置, {})).toBeNull();
    expect(取点击维度(配置, { name: '' })).toBeNull();
    expect(取点击维度(配置, null)).toBeNull();
  });
});

describe('看板联动 · 按条件过滤数据', () => {
  it('单条件过滤', () => {
    const 行 = 按条件过滤数据(配置.数据, [{ 维度: '区域', 值: '华南' }]);
    expect(行).toHaveLength(2);
    expect(行.every(r => r.区域 === '华南')).toBe(true);
  });
  it('多条件 AND；空条件原样返回', () => {
    expect(按条件过滤数据(配置.数据, [{ 维度: '区域', 值: '华东' }, { 维度: '月份', 值: '1月' }])).toHaveLength(1);
    expect(按条件过滤数据(配置.数据, [])).toHaveLength(4);
  });
});

describe('看板联动 · 取下一维度', () => {
  it('排除 X 轴与指标后，返回第一个多值分类列（月份）', () => {
    expect(取下一维度(配置, [])).toBe('月份');
  });
  it('已下钻的维度被排除，到底返回 null', () => {
    expect(取下一维度(配置, [{ 维度: '区域', 值: '华东' }, { 维度: '月份', 值: '1月' }])).toBeNull();
  });
});

describe('看板联动 · 应用下钻', () => {
  it('过滤数据并把 X 轴切到下一维度', () => {
    const 新 = 应用下钻(配置, [{ 维度: '区域', 值: '华东' }]);
    expect(新.X轴).toBe('月份');
    expect(新.数据).toHaveLength(2);
    expect(新.数据.every(r => r.区域 === '华东')).toBe(true);
  });
  it('到底后只过滤，不切换 X 轴；且不修改原对象', () => {
    const 原 = { ...配置, 数据: [...配置.数据] };
    const 新 = 应用下钻(原, [{ 维度: '区域', 值: '华东' }, { 维度: '月份', 值: '1月' }]);
    expect(新.X轴).toBe('区域');
    expect(新.数据).toHaveLength(1);
    expect(原.数据).toHaveLength(4);
  });
});
