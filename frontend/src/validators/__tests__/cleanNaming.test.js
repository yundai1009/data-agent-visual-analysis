/**
 * 阶段 53 · A1：清洗产物默认命名去重。
 *
 * 缺陷（用户走查观察）：重复清洗时默认新名把「已清洗」反复追加，
 * 列表出现「中文销售5万行.csv（已清洗）（已清洗）」这类脏名字。
 * 期望：默认清洗名总是「原名去掉已有标记 + -已清洗」，不再叠加。
 */
import { describe, it, expect } from 'vitest';
import { 默认清洗文件名 } from '../cleanNaming';

describe('默认清洗文件名（阶段 53 回归）', () => {
  it('无标记原名 → 追加 -已清洗', () => {
    expect(默认清洗文件名('销售.csv')).toBe('销售.csv-已清洗');
  });

  it('已带 -已清洗 后缀 → 不再叠加（历史脏名根因）', () => {
    expect(默认清洗文件名('销售.csv-已清洗')).toBe('销售.csv-已清洗');
  });

  it('已带 （已清洗） 后缀 → 归一化为 -已清洗，不叠加', () => {
    expect(默认清洗文件名('销售.csv（已清洗）')).toBe('销售.csv-已清洗');
    expect(默认清洗文件名('销售.csv(已清洗)')).toBe('销售.csv-已清洗');
  });

  it('重复叠加的脏名 → 一次清洗即还原干净', () => {
    expect(默认清洗文件名('中文销售5万行.csv（已清洗）（已清洗）')).toBe('中文销售5万行.csv-已清洗');
    expect(默认清洗文件名('中文销售5万行.csv-已清洗-已清洗')).toBe('中文销售5万行.csv-已清洗');
  });

  it('空值兜底：不抛错，返回可读默认名', () => {
    expect(默认清洗文件名('')).toBe('-已清洗');
    expect(默认清洗文件名(undefined)).toBe('-已清洗');
  });
});