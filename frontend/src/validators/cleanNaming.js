/**
 * validators/cleanNaming.js — 清洗产物默认命名（阶段 53 · A1）
 *
 * 背景：清洗可"另存为新数据集"，默认名 `${原名}-已清洗`。
 * 缺陷：重复清洗时若原名已带「已清洗」标记（-已清洗 或 （已清洗） 两种历史写法），
 *   后缀反复叠加 → 列表出现「xxx（已清洗）（已清洗）」脏名。
 * 规则：先剥离末尾所有「已清洗」标记（兼容 - / （） / () 三种写法），再统一追加
 *   `-已清洗`。保证任意脏名一次清洗即还原干净、永不叠加。
 */

const 已清洗标记 = /(?:[-（(]\s*已清洗\s*[)）]?)+$/;

export function 默认清洗文件名(原名 = '') {
  const base = String(原名).replace(已清洗标记, '');
  return `${base}-已清洗`;
}