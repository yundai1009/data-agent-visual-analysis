def _加载_golden() -> List[Dict[str, Any]]:
    if GOLDEN_PATH.exists():
        with open(GOLDEN_PATH, encoding="utf-8") as f:
            return json.load(f)
    return DEFAULT_GOLDEN


def _保存_golden(items: List[Dict[str, Any]]) -> None:
    GOLDEN_PATH.parent.mkdir(parents=True, exist_ok=True)
    with open(GOLDEN_PATH, "w", encoding="utf-8") as f:
        json.dump(items, f, ensure_ascii=False, indent=2)
    print(f"✅ Golden set 已保存到 {GOLDEN_PATH}")


def _字段匹配(实际: Dict[str, Any], 期望: Dict[str, Any], key: str) -> bool:
    """宽松匹配：None / 空列表 视为等价。"""
    a = 实际.get(key)
    b = 期望.get(key)
    if a == b:
        return True
    # None ↔ 空列表 等价
    if (a is None or a == [] or a == "") and (b is None or b == [] or b == ""):
        return True
    return False


def 评测(verbose: bool = False) -> Dict[str, Any]:
    """运行全部 golden case，返回统计结果。"""
    from 后端_核心.agent.编排器 import 解析自然语言需求

    cases = _加载_golden()
    总用例 = len(cases)
    完全匹配 = 0
    图表匹配 = 0
    x轴匹配 = 0
    y轴匹配 = 0
    聚合匹配 = 0
    总耗时 = 0.0

    for i, case in enumerate(cases):
        需求 = case["需求"]
        画像 = case["画像"]
        期望 = case["期望"]

        start = time.perf_counter()
        try:
            result = 解析自然语言需求(需求, 画像, enable_llm=False)  # 强制走关键词匹配
        except Exception as e:
            if verbose:
                print(f"  ❌ 异常: {e}")
            result = None
        elapsed = (time.perf_counter() - start) * 1000
        总耗时 += elapsed

        if verbose:
            状态 = "✅" if result else "❌"
            print(f"\n  {状态} [{i+1}/{总用例}] {需求} ({elapsed:.0f}ms)")

        if result is None:
            if verbose:
                print(f"      输出: None ❌")
            continue

        # 字段匹配
        ch_match = _字段匹配(result, 期望, "图表类型")
        x_match = _字段匹配(result, 期望, "x轴")
        y_match = result.get("y轴", []) == 期望.get("y轴", [])
        ag_match = _字段匹配(result, 期望, "聚合方式")

        if ch_match:
            图表匹配 += 1
        if x_match:
            x轴匹配 += 1
        if y_match:
            y轴匹配 += 1
        if ag_match:
            聚合匹配 += 1

        full = ch_match and x_match and y_match and ag_match
        if full:
            完全匹配 += 1

        if verbose and not full:
            细节 = []
            if not ch_match: 细节.append(f"图表:{result.get('图表类型')}≠{期望.get('图表类型')}")
            if not x_match: 细节.append(f"x轴:{result.get('x轴')}≠{期望.get('x轴')}")
            if not y_match: 细节.append(f"y轴:{result.get('y轴')}≠{期望.get('y轴')}")
            if not ag_match: 细节.append(f"聚合:{result.get('聚合方式')}≠{期望.get('聚合方式')}")
            print(f"      差异: {'; '.join(细节)}")

    return {
        "总用例": 总用例,
        "完全匹配": 完全匹配,
        "图表类型准确率": f"{图表匹配/总用例*100:.0f}%",
        "X轴命中率": f"{x轴匹配/总用例*100:.0f}%",
        "Y轴命中率": f"{y轴匹配/总用例*100:.0f}%",
        "聚合方式命中率": f"{聚合匹配/总用例*100:.0f}%",
        "完全匹配率": f"{完全匹配/总用例*100:.0f}%",
        "平均耗时(ms)": f"{总耗时/总用例:.1f}",
    }


