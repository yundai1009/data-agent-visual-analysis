# 后端核心模块 - 状态机编排层
# 文件结构说明：
# 状态机_编排_入口.py          - LangGraph 状态机主入口，定义 StateGraph 与节点编排
# 状态机_节点_理解需求.py      - 节点：意图识别、实体抽取、需求结构化
# 状态机_节点_检索上下文.py    - 节点：双分支 RAG 检索（指标口径/历史SQL/分析模板）
# 状态机_节点_生成SQL.py       - 节点：Schema 注入 + Few-shot + LLM 生成 SQL
# 状态机_节点_三层守卫.py      - 节点：语法树校验 → 成本预估 → 运行时熔断
# 状态机_节点_执行查询.py      - 节点：数据库执行、超时控制、结果分页
# 状态机_节点_自动清洗.py      - 节点：缺失值填补、异常值检测、字段标准化
# 状态机_节点_聚合分析.py      - 节点：多维聚合、透视、趋势、同比环比
# 状态机_节点_指标计算.py      - 节点：注册指标函数调用、业务指标产出
# 状态机_节点_可视化推荐.py    - 节点：基于数据特征自动选择图表类型
# 状态机_节点_生成报告.py      - 节点：结构化输出（结论+图表+数据+SQL）
# 状态机_公共_状态定义.py      - 共享状态类、类型定义、常量
# 状态机_公共_异常处理.py      - 统一异常体系、重试策略、熔断器
# 状态机_公共_日志追踪.py      - OpenTelemetry 链路追踪、结构化日志