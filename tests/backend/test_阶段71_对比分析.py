def _月份数据():
    """三份按月分文件的销售数据：地区 × 销售额，无月份列。"""
    一月 = pd.DataFrame({"地区": ["华东", "华南", "华北"], "销售额": [100.0, 80.0, 60.0]})
    二月 = pd.DataFrame({"地区": ["华东", "华南", "华北"], "销售额": [120.0, 70.0, 66.0]})
    三月 = pd.DataFrame({"地区": ["华东", "华南", "华北"], "销售额": [150.0, 84.0, 72.0]})
    return [一月, 二月, 三月], ["1月.csv", "2月.csv", "3月.csv"]


def _地区分文件数据():
    """按地区分文件：每份文件里 地区 列恒定，主体是产品。"""
    华东 = pd.DataFrame({"地区": ["华东", "华东"], "产品": ["A", "B"], "销售额": [500.0, 300.0]})
    华南 = pd.DataFrame({"地区": ["华南", "华南"], "产品": ["A", "B"], "销售额": [200.0, 400.0]})
    return [华东, 华南], ["华东.csv", "华南.csv"]


def test_来源轴_恒定列自动识别():
    """场景：按地区分文件 → 地区列在每个文件里恒定且取值不同，用它当来源轴。"""
    数据, 名称 = _地区分文件数据()
    结果 = 解析来源轴(数据, 名称)
    assert 结果["列"] == "地区"
    assert 结果["标签"] == ["华东", "华南"]
    assert 结果["推导方式"] == "恒定列"
    assert 判定对比轴类型(结果["标签"]) == 轴类型类别


def test_来源轴_单一取值列不误判():
    """回归：每份文件都写死的"公司名称=某某公司"不是来源轴（各集取值相同）。"""
    数据 = [
        pd.DataFrame({"公司名称": ["某某公司", "某某公司"], "部门": ["华东", "华南"], "金额": [1.0, 2.0]}),
        pd.DataFrame({"公司名称": ["某某公司", "某某公司"], "部门": ["华东", "华南"], "金额": [3.0, 4.0]}),
    ]
    结果 = 解析来源轴(数据, ["1月.csv", "2月.csv"])
    assert 结果["列"] is None
    assert 结果["推导方式"] == "文件名"
    assert 结果["标签"] == ["1月", "2月"]


def test_来源轴_无恒定列时用文件名():
    数据, 名称 = _月份数据()
    结果 = 解析来源轴(数据, 名称)
    assert 结果["列"] is None
    assert 结果["标签"] == ["1月", "2月", "3月"]
    assert 判定对比轴类型(结果["标签"]) == 轴类型时间


def test_来源轴_手动标签优先():
    数据, 名称 = _月份数据()
    结果 = 解析来源轴(数据, 名称, 手动标签=["一月", "二月", "三月"])
    assert 结果["标签"] == ["一月", "二月", "三月"]
    assert 结果["推导方式"] == "手动标签"


def test_来源轴_手动标签数量不匹配时忽略():
    数据, 名称 = _月份数据()
    结果 = 解析来源轴(数据, 名称, 手动标签=["只有一个月"])
    assert 结果["推导方式"] == "文件名"


def test_来源轴_指定列不恒定时回落文件名并给警告():
    数据, 名称 = _月份数据()
    结果 = 解析来源轴(数据, 名称, 指定列="地区")
    assert 结果["列"] is None
    assert 结果["推导方式"] == "文件名"
    assert "地区" in 结果["警告"]


def test_来源轴_数值列不被误判为来源轴():
    """回归：单行数据集让"销售额"也满足 nunique<=1，自动识别不得把它当来源轴。"""
    数据 = [
        pd.DataFrame({"地区": ["华东"], "销售额": [0.0]}),
        pd.DataFrame({"地区": ["华东"], "销售额": [50.0]}),
    ]
    assert 解析来源轴(数据, ["1月.csv", "2月.csv"])["列"] is None


def test_来源轴_数值列可被显式指定():
    """整数月份（202401/202402）这类数值型来源列，用户显式指定后应生效。"""
    数据 = [
        pd.DataFrame({"月份": [202401, 202401], "地区": ["华东", "华南"], "销售额": [1.0, 2.0]}),
        pd.DataFrame({"月份": [202402, 202402], "地区": ["华东", "华南"], "销售额": [3.0, 4.0]}),
    ]
    结果 = 解析来源轴(数据, ["a.csv", "b.csv"], 指定列="月份")
    assert 结果["列"] == "月份"
    assert 结果["标签"] == ["202401", "202402"]


