"""阶段 54-9 · Fix L3（LLM P2-3 + 走查 P2）：_可读画像摘要 输出确定性。

走查证据（_stage52_llm_vcr/报告.md P2-1，复现 1x）：
- API 级轮 1 请求与 react_multi_round 录制逐字节一致（命中）；
- 轮 2 因运行时画像摘要不同（质量评级文案「A-优秀」+ 日期 datetime 化
  vs 录制「良好-完整无缺失」+「2026-01」）→ 指纹 miss → 静默降级。

修复语义（方案 A）：`_可读画像摘要` 输出规范化——
- 质量评级用稳定枚举（A/B/C 等级字母，去掉「-优秀/良好」动态说明文案）；
- 日期示例值统一 YYYY-MM-DD 文本，不随 pandas datetime 序列化变化；
- 整型 float 去 `.0`。让「同一数据集不同会话」的画像摘要逐字节一致。
"""

from __future__ import annotations

import os
import sys
from typing import Any, Dict

import pandas as pd

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from 后端_核心.agent.executors import _可读画像摘要  # noqa: E402


def _画像(数据质量: Dict[str, Any] | None = None) -> Dict[str, Any]:
    return {
        "行数": 6,
        "列数": 4,
        "字段列表": ["月份", "地区", "销售额", "订单数"],
        "数值字段": ["销售额", "订单数"],
        "日期字段": ["月份"],
        "分类字段": ["地区"],
        "文本字段": [],
        "数据质量": 数据质量 or {"评级": "A", "等级": "优秀", "等级说明": "数据质量优秀，缺失率 < 5%"},
    }


def _df_日期列datetime() -> pd.DataFrame:
    return pd.DataFrame({
        "月份": pd.to_datetime(["2026-01", "2026-01", "2026-02", "2026-02", "2026-03", "2026-03"]),
        "地区": ["华东", "华南", "华东", "华南", "华东", "华南"],
        "销售额": [100, 80, 120, 90, 110, 95],
        "订单数": [10, 8, 12, 9, 11, 9],
    })


def _df_日期列字符串() -> pd.DataFrame:
    return pd.DataFrame({
        "月份": ["2026-01", "2026-01", "2026-02", "2026-02", "2026-03", "2026-03"],
        "地区": ["华东", "华南", "华东", "华南", "华东", "华南"],
        "销售额": [100, 80, 120, 90, 110, 95],
        "订单数": [10, 8, 12, 9, 11, 9],
    })


# ---- 确定性：同一数据两次调用逐字节一致 ----------------------------------------

def test_可读画像摘要_同一画像两次调用逐字节一致():
    s1 = _可读画像摘要(_画像(), _df_日期列datetime())
    s2 = _可读画像摘要(_画像(), _df_日期列datetime())
    assert s1 == s2, f"同一画像两次调用输出必须逐字节一致：\n{s1!r}\nvs\n{s2!r}"


def test_可读画像摘要_评级行不含动态说明文案():
    """评级只用稳定枚举字母，去掉「-优秀/良好」动态说明文案（等级说明）。"""
    s = _可读画像摘要(_画像(), _df_日期列datetime())
    assert "数据质量评级：A" in s, s
    assert "数据质量优秀" not in s, f"动态说明文案不应进入摘要：{s}"
    assert "缺失率" not in s, f"缺失率文案不应进入摘要：{s}"


# ---- 日期示例值：不随 pandas datetime 序列化变化 ----------------------------------

def test_可读画像摘要_日期列datetime_统一YYYYMMDD():
    s = _可读画像摘要(_画像(), _df_日期列datetime())
    assert "月份: 2026-01-01, 2026-01-01, 2026-02-01" in s, f"datetime 应渲染为 YYYY-MM-DD：{s}"
    assert "2026-01-01 00:00:00" not in s, f"不得出现 pandas 默认 datetime 序列化：{s}"


def test_可读画像摘要_日期列字符串_原样保留():
    s = _可读画像摘要(_画像(), _df_日期列字符串())
    assert "月份: 2026-01, 2026-01, 2026-02" in s, s


# ---- 评级缺失时回退等级标签（仍确定性） ------------------------------------------

def test_可读画像摘要_评级缺失_用等级标签():
    画像 = _画像(数据质量={"等级": "优秀", "等级说明": "动态文案"})
    s1 = _可读画像摘要(画像, _df_日期列字符串())
    s2 = _可读画像摘要(画像, _df_日期列字符串())
    assert s1 == s2
    assert "数据质量评级：优秀" in s1, s1


# ---- 整型 float 归一（示例值不带 .0，跨会话稳定） ---------------------------------

def test_可读画像摘要_整型float示例值去点():
    df = pd.DataFrame({"销售额": [100.0, 80.0, 120.0]})
    画像 = {
        "行数": 3, "列数": 1,
        "字段列表": ["销售额"], "数值字段": ["销售额"],
        "日期字段": [], "分类字段": [],
        "数据质量": {"评级": "A", "等级": "优秀"},
    }
    s = _可读画像摘要(画像, df)
    assert "销售额: 100, 80, 120" in s, s
