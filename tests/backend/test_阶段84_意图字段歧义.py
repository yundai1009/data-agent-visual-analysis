# -*- coding: utf-8 -*-
"""阶段八十四 · 意图字段歧义回归（第 12 项）

用户反馈：说"会员等级占比"，生成的却是"会员地区占比"，且同类选错字段在多种
需求里反复出现。根因不是关键词数量不够，而是 `_匹配意图字段` 依赖固定关键词
顺序 + 字段名子串匹配：词表里没有"等级"，"地区"先命中"会员地区"，把真实维度顶掉。

修复：需求文本里**整串出现某个完整字段名**时，取最长匹配，优先于关键词表。
本文件锁死该行为，防止回退。
"""
from __future__ import annotations

import sys
from pathlib import Path

PROJECT_ROOT = str(Path(__file__).resolve().parent.parent)
if PROJECT_ROOT not in sys.path:
    sys.path.insert(0, PROJECT_ROOT)

from 后端_核心.field_selector import _匹配意图字段, _受控语句配置  # noqa: E402


def _画像(字段列表, 分类字段):
    return {
        "行数": 100,
        "列数": len(字段列表),
        "字段列表": 字段列表,
        "数值字段": [f for f in 字段列表 if f not in 分类字段],
        "分类字段": 分类字段,
        "日期字段": [],
        "文本字段": [],
    }


# ═══ 1. 直接字段名命中（核心修复）═══

def test_会员等级占比_命中会员等级而非会员地区():
    画像 = _画像(["会员等级", "会员地区", "订单金额"], ["会员等级", "会员地区"])
    assert _匹配意图字段(画像, ["占比"], "会员等级占比图") == "会员等级"


def test_会员地区占比_仍命中会员地区():
    画像 = _画像(["会员等级", "会员地区", "订单金额"], ["会员等级", "会员地区"])
    assert _匹配意图字段(画像, ["占比"], "会员地区占比图") == "会员地区"


def test_字段名整串出现_取最长匹配():
    画像 = _画像(["会员等级", "会员等级名称"], ["会员等级", "会员等级名称"])
    # 需求只写了"会员等级"，"会员等级名称"并未整串出现 → 命中较短的"会员等级"
    assert _匹配意图字段(画像, ["等级"], "会员等级占比") == "会员等级"


def test_新维度词_级别可被关键词命中():
    画像 = _画像(["级别", "地区", "销售额"], ["级别", "地区"])
    # 需求文本里字段名"级别"整串出现 → 直接命中
    assert _匹配意图字段(画像, ["级别"], "按级别占比") == "级别"


def test_新维度词_组别通过关键词兜底命中():
    画像 = _画像(["班组成员", "地区", "销售额"], ["班组成员", "地区"])
    # 需求写"班组"但字段全名是"班组成员"（整串没出现）→ 走关键词子串兜底命中
    assert _匹配意图字段(画像, ["班组"], "按班组占比") == "班组成员"


# ═══ 2. 端到端：占比需求选对维度字段 ═══

def test_受控语句_会员等级占比_x轴选对():
    画像 = _画像(["会员等级", "会员地区", "订单金额"], ["会员等级", "会员地区"])
    out = _受控语句配置(画像, "会员等级占比图")
    assert out["x轴"] == "会员等级"


def test_受控语句_会员地区占比_x轴仍对():
    画像 = _画像(["会员等级", "会员地区", "订单金额"], ["会员等级", "会员地区"])
    out = _受控语句配置(画像, "会员地区占比图")
    assert out["x轴"] == "会员地区"


# ═══ 3. 无直接字段名时行为不变（向下兼容）═══

def test_无直接命中时仍走原关键词顺序():
    画像 = _画像(["列车类型", "销售额"], ["列车类型"])
    # 需求写"类型"，字段全名"列车类型"未整串出现 → 走关键词子串兜底
    assert _匹配意图字段(画像, ["类型"], "按类型占比") == "列车类型"
