# -*- coding: utf-8 -*-
"""阶段七十四 · A 批（图表可读性 + 图表标题）：纯函数级回归。

背景：上线后收到的用户反馈里，P1 两条都指向「图看不明白」——
① 图表必须把鼠标悬浮上去才看得见类别和占比；
② 自动生成的图表标题概括不了图表内容。

对应两处改动：
- ① 前端 `frontend/src/components/EChartsChart.jsx` 的标签默认开启（由
  `EChartsChart.test.jsx` 覆盖，本文件不重复）。
- ② 后端 `_生成图表标题`（本文件覆盖）——它产出的是**子标题**：
  标题继续是用户原话（`chart_config["标题"]` 契约不变，四处既有断言锁死），
  子标题补「按哪个维度、哪个指标、什么口径」，两者一起才把图说清楚。

刻意的设计取舍（面试可讲）：不去改标题契约，而是新增一层。
理由是那四处断言里有两条本身是对的度量——长需求必须截断成 60 字，
追问产生的标题不得被上文污染；为了"标题更好看"去放宽它们，等于用产品话术
换掉两条真实约束。
"""
import sys
from pathlib import Path

import pandas as pd
import pytest

仓库 = Path(__file__).resolve().parents[2]
if str(仓库) not in sys.path:
    sys.path.insert(0, str(仓库))

from 后端_核心.report_generator import _生成图表标题  # noqa: E402


数据 = pd.DataFrame({
    "地区": ["华东", "华北"],
    "销售额": [100, 150],
    "渠道": ["线上", "线下"],
})


class Test占比如类图表:
    def test_饼图讲占比不讲数值(self):
        结果 = _生成图表标题("那华南区呢", "饼图", "地区", ["销售额"], None, "求和", 数据)
        assert 结果 == "按地区拆分 销售额 的占比"

    def test_环形图与饼图同一口径(self):
        assert _生成图表标题("x", "环形图", "地区", ["销售额"], None, "求和", 数据) == \
            "按地区拆分 销售额 的占比"


class Test有分组维度:
    def test_分组柱状图把分组列说出来(self):
        结果 = _生成图表标题("按地区和渠道看销售额", "柱状图", "地区", ["销售额"], "渠道", "求和", 数据)
        assert 结果 == "按地区、渠道分组求和的销售额"

    def test_热力图用叉乘表达两个维度(self):
        assert _生成图表标题("x", "热力图", "地区", ["销售额"], "渠道", "平均值", 数据) == \
            "地区 × 渠道 的销售额分布"


class Test无分组:
    def test_普通柱状图带聚合口径(self):
        assert _生成图表标题("x", "柱状图", "地区", ["销售额"], None, "平均值", 数据) == \
            "按地区分组平均的销售额"

    def test_聚合方式留空时不硬凑口径(self):
        assert _生成图表标题("x", "柱状图", "地区", ["销售额"], None, "", 数据) == \
            "按地区分组的销售额"


class Test其它图表:
    def test_散点图讲相关关系(self):
        assert _生成图表标题("x", "散点图", "月份", ["销售额"], None, "", 数据) == \
            "月份 与 销售额 的相关关系"

    def test_词云不要在词频上再叠词频(self):
        assert _生成图表标题("x", "词云", None, ["词频"], None, "", 数据) == "词频分布"

    def test_只有X轴时退化成分布(self):
        assert _生成图表标题("x", "柱状图", "地区", [], None, "", 数据) == "按地区的分布"


class Test兜底:
    def test_什么都没有时返回空串而不是None(self):
        # 空串让调用方（chart_config）跳过写 子标题，前端会自己兜一个默认值
        结果 = _生成图表标题("", "table", None, [], None, "", pd.DataFrame())
        assert 结果 == ""
        assert isinstance(结果, str)

    def test_英文聚合方式也认(self):
        # LLM 有时给 sum/mean/count，不做语言特判就要么不显示口径、要么显示原词
        assert _生成图表标题("x", "柱状图", "地区", ["销售额"], None, "mean", 数据) == \
            "按地区分组平均的销售额"
        assert _生成图表标题("x", "柱状图", "地区", ["销售额"], None, "count", 数据) == \
            "按地区分组计数的销售额"


class Test不抢标题的活:
    def test_子标题不是用户原话的复制(self):
        # 这条是本次改动的核心：过去的"标题"就是用户原话，所以"那华南区呢"这种
        # 半个问句会直接上图。子标题必须说数据，不能再说一遍问题。
        原话 = "那华南区呢？"
        assert _生成图表标题(原话, "饼图", "地区", ["销售额"], None, "求和", 数据) != 原话
        assert "地区" in _生成图表标题(原话, "饼图", "地区", ["销售额"], None, "求和", 数据)

    def test_图表类型未知时不炸(self):
        结果 = _生成图表标题("x", "某个没见过的图", "地区", ["销售额"], None, "", 数据)
        assert 结果 == "按地区分组的销售额"
