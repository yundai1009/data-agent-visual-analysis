// 托盘右键菜单的结构计算（纯函数）：main.js 只负责把这里算出的项映射成各自的 click 行为。
// 做了什么：托盘菜单(state) 返回「显示主窗口」「配置…」/ 分割线 /「退出」四项，每项形如 { id, label, type }；
//   id 是 main.js 分发点击行为的唯一依据（show / config / quit），label 只负责显示。
// 为什么菜单模板要抽成纯函数：Electron 的 Tray / Menu 只有 app ready 之后才能建，
//   菜单项的顺序、文案、「有没有配置入口」这类回归只能靠真机点一次托盘才能发现；抽出来后 node --test 能对整个数组做断言。
// 为什么「配置…」放托盘而不是放主窗口里：托盘常驻时主窗口的常态是「隐藏」而不是「最小化」（关窗口只 hide），
//   而配置是低频但关键的操作——后端起不来时它是唯一界面——必须有一条不依赖主窗口可见的入口。
// 为什么 state 入参保留但今天不参与分支：菜单结构将来要随窗口可见性演化（比如隐藏时改文案为「打开主窗口」），
//   先把签名定下来，免得以后改契约要连带 main.js 一起动；现在不用是因为 show 走的都是 show+focus 同一套逻辑。
// 坑：只有 id 的语义被消费，改 label 不影响 main.js，改 id 会让菜单项「点了没反应」——两侧必须同步。
function 托盘菜单(state) {
  // 菜单 label 当前固定为「显示主窗口」（点击时总是 show+focus，见 main.js 映射）；
  // state 保留入参以描述菜单结构可随窗口可见性演化的契约。
  // 「配置…」= 桌面版可视化配置窗口（数据库模式 / 认证模式）；
  // 放在「显示主窗口」旁边而不是窗口里，是因为托盘常驻时主窗口常态是隐藏的，
  // 而配置是低频但关键的操作，必须有一条不依赖主窗口可见的入口。
  return [
    { id: 'show', label: '显示主窗口', type: 'normal' },
    { id: 'config', label: '配置…', type: 'normal' },
    { id: 'separator', type: 'separator' },
    { id: 'quit', label: '退出', type: 'normal' },
  ];
}

module.exports = { 托盘菜单 };
